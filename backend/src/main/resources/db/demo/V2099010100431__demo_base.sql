-- 12. Movimientos INITIAL en stock_movements (RN-02)
--     Garantiza SUM(quantity_delta) = stock.quantity por cada fila de stock.
-- -----------------------------------------------------------------------------
INSERT INTO stock_movements
    (store_id, product_id, lot_id, movement_type, quantity_delta, balance_after, unit_cost, source_type, source_id, reason, user_id, occurred_at)
SELECT
    st.store_id,
    st.product_id,
    NULL,
    'INITIAL',
    st.quantity,
    st.quantity,
    p.avg_cost,
    'INITIAL_LOAD',
    p.id,
    'Carga inicial de inventario demo (T43)',
    a.id,
    now()
FROM stock st
JOIN products p ON p.id = st.product_id
CROSS JOIN (SELECT id FROM users WHERE lower(username) = 'admin') a
WHERE st.quantity > 0
  AND NOT EXISTS (
      SELECT 1 FROM stock_movements sm
      WHERE sm.store_id = st.store_id
        AND sm.product_id = st.product_id
        AND sm.movement_type = 'INITIAL'
  );
